"""Code generator orchestrator (M6)."""
from __future__ import annotations
import json
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List
from animation_engine.timeline import build_animation_timeline
from .options import GeneratorOptions
from .css_builder import build_css
from .tailwind_config import build_tailwind_config
from .js_builder import build_js
from .html_builder import build_html

@dataclass
class BundleResult:
    out_dir: Path
    files: List[Path] = field(default_factory=list)
    total_ms: int = 0

    def to_dict(self):
        return {"out_dir": str(self.out_dir), "files": [str(p) for p in self.files], "total_ms": self.total_ms}

def _readme(options, total_ms):
    return f"""# {options.title}

Generated by **StrokeForge** (M6).

Open `index.html` in any modern browser. No build step, no server.

## Playback defaults
- autoplay: `{options.autoplay}`
- loop: `{options.loop}`
- loop delay: `{options.loop_delay_ms} ms`
- speed: `{options.speed}x`
- gap: `{options.gap_ms} ms`
- total: `{total_ms} ms`
"""

def generate_bundle(styled_doc, out_dir, options: GeneratorOptions) -> BundleResult:
    out_dir = Path(out_dir); bundle = out_dir / options.name; bundle.mkdir(parents=True, exist_ok=True)
    timeline = build_animation_timeline(styled_doc, speed=options.speed, gap_ms=options.gap_ms,
                                        loop=options.loop, loop_delay_ms=options.loop_delay_ms)
    files: List[Path] = []
    (bundle / "index.html").write_text(build_html(styled_doc, options), encoding="utf-8"); files.append(bundle / "index.html")
    (bundle / "styles.css").write_text(build_css(styled_doc), encoding="utf-8"); files.append(bundle / "styles.css")
    (bundle / "script.js").write_text(build_js(styled_doc, timeline, options.to_dict()), encoding="utf-8"); files.append(bundle / "script.js")
    (bundle / "tailwind.config.js").write_text(build_tailwind_config(styled_doc), encoding="utf-8"); files.append(bundle / "tailwind.config.js")
    if options.include_animation_json:
        (bundle / "data.json").write_text(json.dumps(timeline.to_dict(), indent=2), encoding="utf-8"); files.append(bundle / "data.json")
    if options.include_readme:
        (bundle / "README.md").write_text(_readme(options, timeline.total_ms), encoding="utf-8"); files.append(bundle / "README.md")
    return BundleResult(out_dir=bundle, files=files, total_ms=timeline.total_ms)